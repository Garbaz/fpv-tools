"""Generate src/fpv_tools/fc/msp_codes.py from a Betaflight source tree.

uv run scripts/gen_msp_codes.py path/to/betaflight
"""

import re
import subprocess
import sys
from pathlib import Path

HEADERS = ("msp_protocol.h", "msp_protocol_v2_common.h", "msp_protocol_v2_betaflight.h")
DEFINE = re.compile(r"^#define\s+(MSP2?_[A-Z0-9_]+)\s+(0x[0-9A-Fa-f]+|\d+)\s*(?://\s*(.*))?$")
# Constants in these headers that are not message codes
NOT_MESSAGES = re.compile(
    r"^MSP_(PROTOCOL_VERSION|API_VERSION_MAJOR|API_VERSION_MINOR|API_VERSION_LENGTH|.*_IDENTIFIER|.*_LENGTH)$|^MSP2TEXT_"
)
# msp/msp.c functions for messages sent to the FC to change something. Messages answered elsewhere can change
# things too (MSP_REBOOT, MSP_RESET_CONF, MSP_SET_PASSTHROUGH): firmware/msp_effects.py lists those by hand.
INBOUND_HANDLERS = ("mspProcessInCommand", "mspCommonProcessInCommand")
HANDLED = re.compile(r"\bcase\s+(MSP2?_[A-Z0-9_]+)\s*:|\bcmdMSP\s*==\s*(MSP2?_[A-Z0-9_]+)")


def _show(source: Path, ref: str, path: str) -> str:
    command = ["git", "-C", str(source), "show", f"{ref}:{path}"]
    return subprocess.run(command, capture_output=True, text=True, check=True).stdout


def _body(text: str, function: str) -> str:
    """The body of a C function definition (not its prototype), by brace matching."""
    for m in re.finditer(rf"^\w[\w ]*\b{function}\([^;{{]*\)\s*{{", text, re.M):
        depth, i = 1, m.end()
        while depth:
            depth += {"{": 1, "}": -1}.get(text[i], 0)
            i += 1
        return text[m.end() : i - 1]
    raise SystemExit(f"msp/msp.c: no definition of {function}")


def inbound(source: Path, ref: str, codes: dict[str, tuple[int, str]]) -> list[str]:
    text = _show(source, ref, "src/main/msp/msp.c")
    names = [a or b for f in INBOUND_HANDLERS for a, b in HANDLED.findall(_body(text, f))]
    unknown = sorted({n for n in names if n not in codes})
    if unknown:
        raise SystemExit(f"msp/msp.c handles messages msp_protocol*.h does not define: {unknown}")
    return sorted(set(names), key=lambda n: codes[n][0])


def main(source: Path, ref: str) -> None:
    codes: dict[str, tuple[int, str]] = {}
    for header in HEADERS:
        text = _show(source, ref, f"src/main/msp/{header}")
        for line in text.splitlines():
            if (m := DEFINE.match(line.strip())) and not NOT_MESSAGES.match(m.group(1)):
                codes[m.group(1)] = (int(m.group(2), 0), (m.group(3) or "").strip())
    version = (
        f"{ref} "
        + subprocess.run(
            ["git", "-C", str(source), "log", "-1", "--format=%h %cs", ref], capture_output=True, text=True, check=True
        ).stdout.strip()
    )
    handled = inbound(source, ref, codes)
    lines = [
        f'"""MSP message codes from Betaflight {version or "?"} msp/msp_protocol*.h,',
        "and the messages msp/msp.c handles in its inbound handlers.",
        "",
        'Generated by scripts/gen_msp_codes.py."""',
        "",
        "CODES: dict[str, int] = {",
        *(
            f"    {name!r}: {code},  # {comment}" if comment else f"    {name!r}: {code},"
            for name, (code, comment) in codes.items()
        ),
        "}",
        "",
        "NAMES: dict[int, str] = {code: name for name, code in CODES.items()}",
        "",
        f"# {', '.join(INBOUND_HANDLERS)}",
        "INBOUND: frozenset[str] = frozenset({",
        *(f"    {name!r}," for name in handled),
        "})",
        "",
    ]
    out = Path(__file__).resolve().parents[1] / "src" / "fpv_tools" / "fc" / "msp_codes.py"
    out.write_text("\n".join(lines))
    print(f"{out}: {len(codes)} codes, {len(handled)} inbound", file=sys.stderr)


if __name__ == "__main__":
    main(Path(sys.argv[1]).expanduser(), sys.argv[2] if len(sys.argv) > 2 else "origin/2026.6-maintenance")
